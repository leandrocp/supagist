const root = new URL("../../../../", import.meta.url);
const generated = new URL("./generated/", import.meta.url);
const assets = new URL("../assets/", import.meta.url);
await Promise.all([mkdir(generated, { recursive: true }), mkdir(assets, { recursive: true })]);
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");
// Asset-only refresh avoids unrelated installed parser metadata drift (e.g. LLVM)
// when no app/vendor regeneration is needed. The default still prepares everything.
if (process.argv.includes("--assets-only")) {
  const manifest = JSON.parse(await readFile(new URL("manifest.json", assets), "utf8"));
  await prepareBrandAssets(manifest);
  await writeFile(new URL("manifest.json", assets), JSON.stringify(manifest, null, 2) + "\n");
  console.log(
    "Prepared brand fonts, licenses and images only; app/vendor/parser outputs unchanged.",
  );
  process.exit(0);
}
for (const [pkg, version] of [
  ["lumis", "0.10.1"],
  ["themes", "0.4.3"],
]) {
  const installed = JSON.parse(
    await readFile(new URL(`node_modules/@lumis-sh/${pkg}/package.json`, root)),
  );
  if (installed.version !== version) throw new Error(`M0 requires ${pkg}@${version}`);
}

function replaceOnce(source, before, after) {
  if (source.split(before).length !== 2) throw new Error(`App seam drifted: ${before}`);
  return source.replace(before, after);
}

const sources = {};
for (const name of [
  "export-utils",
  "snippet-utils",
  "lumis-lines",
  "presence-utils",
  "brand-presets",
  "brand-scenes",
  "export-metadata",
  "brand-themes",
]) {
  let source = await readFile(new URL(`lib/${name}.ts`, root), "utf8");
  sources[`lib/${name}.ts`] = digest(source);
  if (name === "export-utils") {
    const start = source.indexOf("const fontBase64Cache =");
    const end = source.indexOf("// Pick a readable text colour", start);
    if (start < 0 || end < 0) throw new Error("Asset seams drifted");
    source =
      source.slice(0, start) +
      'import { loadFontBase64, loadImageDataUrl } from "../assets.ts";\nconst loadAvatarDataUrl = loadImageDataUrl;\n\n' +
      source.slice(end);
    source = replaceOnce(source, "data:font/woff2;base64,", "data:font/ttf;base64,");
    source = replaceOnce(source, "format('woff2')", "format('truetype')");
  }
  if (name === "lumis-lines") {
    const start = source.indexOf("  try {\n    await highlighter.loadLanguage(language);");
    const end = source.indexOf("\n}\n", start);
    if (start < 0 || end < 0) throw new Error("Strict preload seam drifted");
    source =
      source.slice(0, start) +
      "  await highlighter.loadLanguage(language);\n  return language;" +
      source.slice(end);
  }
  source = source
    .replaceAll('"@/lib/lumis-client"', '"../lumis-client.ts"')
    .replaceAll('"@/lib/theme-loader"', '"../theme-loader.ts"')
    .replace(/"@\/lib\/([^"\n]+)"/g, '"./$1.js"')
    .replace(/"@lumis-sh\/lumis([^"\n]*)"/g, '"./vendor/lumis.js"');
  await writeFile(
    new URL(`${name}.js`, generated),
    "// Generated by prepare-render.mjs; do not edit.\n" +
      stripTypeScriptTypes(source, { mode: "strip" }),
  );
}

// Ship exact package metadata (including queries, version, parser digest), not parsers.
