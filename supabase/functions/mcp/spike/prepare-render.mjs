const assetManifest = {};
for (const [name, url, sha256] of downloads) {
  let bytes;
  try {
    bytes = await readFile(new URL(name, assets));
  } catch {
    /* first preparation */
  }
  if (!bytes || digest(bytes) !== sha256) {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`Asset download ${response.status}: ${url}`);
    bytes = Buffer.from(await response.arrayBuffer());
  }
  if (digest(bytes) !== sha256) throw new Error(`Asset integrity mismatch: ${name}`);
  await writeFile(new URL(name, assets), bytes);
  assetManifest[name] = { url, sha256, bytes: bytes.length };
}

// Original, deterministic pixel portraits: real PNG images, not SVG initials.
// No remote user/avatar URL is accepted by the renderer.
function crc32(bytes) {
  let crc = 0xffffffff;
  for (const byte of bytes) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const tag = Buffer.from(type);
  const size = Buffer.alloc(4);
  size.writeUInt32BE(data.length);
  const checksum = Buffer.alloc(4);
  checksum.writeUInt32BE(crc32(Buffer.concat([tag, data])));
  return Buffer.concat([size, tag, data, checksum]);
}
for (let face = 0; face < 2; face++) {
  const rows = Buffer.alloc(32 * (1 + 32 * 3));
  for (let y = 0; y < 32; y++)
    for (let x = 0; x < 32; x++) {
      let rgb = face ? [85, 130, 175] : [126, 88, 162];
      if ((x - 16) ** 2 + (y - 14) ** 2 < 85) rgb = face ? [152, 94, 64] : [238, 188, 142];
      if (y > 24 && Math.abs(x - 16) < y - 15) rgb = face ? [42, 62, 86] : [54, 108, 82];
      if (y > 5 && y < 10 && Math.abs(x - 16) < 8) rgb = [48, 35, 30];
      if (y === 14 && (x === 12 || x === 20)) rgb = [20, 20, 20];
      if (y === 20 && x > 13 && x < 19) rgb = [85, 35, 35];
      rows.set(rgb, y * 97 + 1 + x * 3);
    }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(32, 0);
  header.writeUInt32BE(32, 4);
  header[8] = 8;
  header[9] = 2;
  const bytes = Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", header),
    chunk("IDAT", deflateSync(rows)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
  const name = `avatar-${face + 1}.png`;
  await writeFile(new URL(name, assets), bytes);
  assetManifest[name] = {
    provenance: "Original M0 pixel portrait, generated by this script; repository MIT license",
    sha256: digest(bytes),
    bytes: bytes.length,
  };
}
await prepareBrandAssets(assetManifest);
